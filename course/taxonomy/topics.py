def extract(*texts: str | None) -> list[str]:
    """從任意段文字抽出主題標籤，順序穩定、不重複。"""
    blob = " ".join(t for t in texts if t)
    if not blob:
        return []
    low = blob.lower()
    out: list[str] = []
    for label, needles in PATTERNS.items():
        if any((n.lower() in low) for n in needles) and label not in out:
            out.append(label)
    return out
